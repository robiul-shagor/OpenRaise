// Copies ABIs from Foundry build output and deployment addresses into src/generated/contracts.ts.
// Usage: (cd ../contracts && forge build) && node scripts/sync-contracts.mjs
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "contracts");
const abi = (name) => JSON.parse(readFileSync(join(root, "out", `${name}.sol`, `${name}.json`), "utf8")).abi;

const deploymentsDir = join(root, "deployments");
const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const file of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, file), "utf8"));
    if (d.chainId === 1) continue; // never wire mainnet
    deployments[d.chainId] = {
      openRaise: d.openRaise,
      mockToken: d.mockToken,
      startBlock: String(d.startBlock),
    };
  }
}

const out = `// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit by hand.
export const openRaiseAbi = ${JSON.stringify(abi("OpenRaise"), null, 2)} as const;

export const mockErc20Abi = ${JSON.stringify(abi("MockERC20"), null, 2)} as const;

export const deployments: Record<number, { openRaise: \`0x\${string}\`; mockToken: \`0x\${string}\`; startBlock: string }> = ${JSON.stringify(deployments, null, 2)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "..", "src", "generated", "contracts.ts"), out);
console.log(`Synced ABIs and ${Object.keys(deployments).length} deployment(s).`);
